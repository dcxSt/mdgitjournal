#!/bin/sh
# Regenerates packaging/THIRD-PARTY-NOTICES.md: the licences of everything compiled into the app.
# Run it after changing dependencies, and commit the result; CI checks that it is up to date.
#
# Needs jq, cargo-about (cargo install cargo-about --version 0.9.3 --locked --features cli), the
# crates (cargo fetch --locked) and the UI's dependencies (pnpm -C app install). It reads only
# local files.
set -eu
export LC_ALL=C
cd "$(dirname "$0")/../.."
here=packaging/notices
out=packaging/THIRD-PARTY-NOTICES.md
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Prints a licence text as a fenced block.
fence() { printf '```text\n'; cat "$1"; printf '\n```\n\n'; }

# Prints the directory of a crate in the local cargo registry.
crate_dir() {
  cargo metadata --frozen --format-version 1 |
    jq -r --arg name "$1" '.packages[] | select(.name == $name) | .manifest_path' |
    xargs dirname
}

{
  cat <<'EOF'
# Third-party notices

mdgitjournal is MIT licensed (see LICENSE). It includes the software below, under the licences
that follow.

This software is based in part on the work of the Independent JPEG Group.

<!-- Generated by packaging/notices/generate.sh; don't edit by hand. -->

EOF

  cargo about generate --frozen --workspace -c "$here/about.toml" "$here/about.hbs"

  # The -sys crates' own licences don't cover the C libraries they compile in.
  echo "## C libraries"
  echo
  echo "### libgit2, built into libgit2-sys"
  echo
  fence "$(crate_dir libgit2-sys)/libgit2/COPYING"
  echo "### OpenSSL, built into openssl-src"
  echo
  fence "$(crate_dir openssl-src)/openssl/LICENSE.txt"

  # The npm packages in the UI bundle, as listed in its source maps.
  pnpm -C app exec vite build --sourcemap --outDir "$tmp/dist" --emptyOutDir --logLevel warn >&2
  jq -r '.sources[]' "$tmp"/dist/assets/*.map |
    sed -nE 's#^.*/node_modules/\.pnpm/([^/]+)/node_modules/((@[^/]+/)?[^/]+)/.*$#app/node_modules/.pnpm/\1/node_modules/\2#p' |
    sort -u > "$tmp/packages"
  [ -s "$tmp/packages" ] || { echo "no npm packages found in the source maps" >&2; exit 1; }

  echo "## npm packages"
  echo
  while read -r dir; do
    jq -r '"### \(.name) \(.version)\n\nLicence: \(.license // "not stated").\n"' "$dir/package.json"
    files=$(find "$dir" -maxdepth 1 -type f \( -iname 'licen[cs]e*' -o -iname 'copying*' -o -iname 'notice*' \) | sort)
    [ -n "$files" ] || printf 'The package contains no licence file.\n\n'
    for file in $files; do fence "$file"; done
  done < "$tmp/packages"
} > "$tmp/notices.md"

mv "$tmp/notices.md" "$out"
echo "wrote $out" >&2
